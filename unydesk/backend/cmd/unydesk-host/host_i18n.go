func hostLocaleCode() string {
	hostLocaleOnce.Do(func() {
		hostLocale = normalizeHostLocaleCode(detectSystemLocaleCode())
	})
	return hostLocale
}

func normalizeHostLocaleCode(value string) string {
	value = strings.ToLower(strings.TrimSpace(value))
	switch {
	case strings.HasPrefix(value, "fr"):
		return hostLocaleFR
	case strings.HasPrefix(value, "de"):
		return hostLocaleDE
	default:
		return hostLocaleEN
	}
}

func hostLocaleStrings(locale string) map[string]string {
	base := hostLocaleCatalogs[hostLocaleEN]
	merged := make(map[string]string, len(base))
	for key, value := range base {
		merged[key] = value
	}
	if locale != hostLocaleEN {
		if overrides, ok := hostLocaleCatalogs[locale]; ok {
			for key, value := range overrides {
				merged[key] = value
			}
		}
	}
	return merged
}

func hostText(key string) string {
	hostTextsOnce.Do(func() {
		hostTexts = hostLocaleStrings(hostLocaleCode())
	})
	if value := strings.TrimSpace(hostTexts[key]); value != "" {
		return value
	}
	if fallback := strings.TrimSpace(hostLocaleCatalogs[hostLocaleEN][key]); fallback != "" {
		return fallback
	}
	return key
}

func hostTextf(key string, args ...any) string {
	return fmt.Sprintf(hostText(key), args...)
}

func hostUITextJSON() string {
	payload, err := json.Marshal(hostLocaleStrings(hostLocaleCode()))
	if err != nil {
		return "{}"
	}
	return string(payload)
}
